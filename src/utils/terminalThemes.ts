/** Looks up a preset; unknown ids resolve to the default vivid preset. */
export function getTerminalPreset(id: string): TerminalThemePreset {
  return (
    TERMINAL_THEME_PRESETS.find((preset) => preset.id === id) ??
    TERMINAL_THEME_PRESETS.find((preset) => preset.id === FALLBACK_PRESET_ID) ??
    TERMINAL_THEME_PRESETS[0]
  );
}

// Hex alpha appended to the opaque selection colour (0x52 / 0xff = 32 %).
const SELECTION_ALPHA = '52';

export function toXtermTheme(colors: TerminalColors): ITheme {
  return {
    background: colors.background,
    foreground: colors.foreground,
    cursor: colors.cursor,
    cursorAccent: colors.background,
    selectionBackground: colors.selectionBackground + SELECTION_ALPHA,
    black: colors.black,
    red: colors.red,
    green: colors.green,
    yellow: colors.yellow,
    blue: colors.blue,
    magenta: colors.magenta,
    cyan: colors.cyan,
    white: colors.white,
    brightBlack: colors.brightBlack,
    brightRed: colors.brightRed,
    brightGreen: colors.brightGreen,
    brightYellow: colors.brightYellow,
    brightBlue: colors.brightBlue,
    brightMagenta: colors.brightMagenta,
    brightCyan: colors.brightCyan,
    brightWhite: colors.brightWhite,
  };
}
